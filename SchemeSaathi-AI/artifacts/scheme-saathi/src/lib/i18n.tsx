interface LanguageContextType {
  lang: LanguageCode;
  setLang: (lang: LanguageCode) => void;
  t: (key: string, defaultText?: string) => string;
}

const LanguageContext = createContext<LanguageContextType>({
  lang: 'en',
  setLang: () => {},
  t: (key, defaultText) => defaultText || key,
});

export function LanguageProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<LanguageCode>(() => {
    if (typeof localStorage !== 'undefined') {
      const saved = localStorage.getItem('schemesaathi_lang') as LanguageCode;
      if (saved && TRANSLATIONS[saved]) return saved;
    }
    return 'en';
  });

  useEffect(() => {
    const handleLangChange = (e: CustomEvent<string>) => {
      const newLang = e.detail as LanguageCode;
      if (newLang && TRANSLATIONS[newLang]) {
        setLangState(newLang);
      }
    };

    window.addEventListener('schemesaathi-lang-change', handleLangChange as EventListener);
    return () => {
      window.removeEventListener('schemesaathi-lang-change', handleLangChange as EventListener);
    };
  }, []);

  const setLang = (newLang: LanguageCode) => {
    if (TRANSLATIONS[newLang]) {
      setLangState(newLang);
      if (typeof localStorage !== 'undefined') {
        localStorage.setItem('schemesaathi_lang', newLang);
      }
      window.dispatchEvent(new CustomEvent('schemesaathi-lang-change', { detail: newLang }));
    }
  };

  const t = (key: string, defaultText?: string): string => {
    const langDict = TRANSLATIONS[lang] || TRANSLATIONS.en;
    if (langDict && langDict[key]) {
      return langDict[key];
    }
    if (TRANSLATIONS.en && TRANSLATIONS.en[key]) {
      return TRANSLATIONS.en[key];
    }
    return defaultText || key;
  };

  return (
    <LanguageContext.Provider value={{ lang, setLang, t }}>
      {children}
    </LanguageContext.Provider>
  );
}

export function useLanguage() {
  return useContext(LanguageContext);
}
